CREATE TABLE VOLUNTARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL UNIQUE,
    CPF VARCHAR2(11) NOT NULL UNIQUE,
    DATA_NASCIMENTO DATE NOT NULL,
    ESTADO VARCHAR2(2) NOT NULL,
    CIDADE VARCHAR2(100) NOT NULL,
    BAIRRO VARCHAR2(100),
    CONSTRAINT FK_VOL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE BENEFICIARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL UNIQUE,
    CPF VARCHAR2(11) NOT NULL UNIQUE,
    DATA_NASCIMENTO DATE NOT NULL,
    ESTADO VARCHAR2(2) NOT NULL,
    CIDADE VARCHAR2(100) NOT NULL,
    BAIRRO VARCHAR2(100),
    CONSTRAINT FK_BEN_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE ONGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL UNIQUE,
    CNPJ VARCHAR2(14) NOT NULL UNIQUE,
    NOME_RESPONSAVEL VARCHAR2(120) NOT NULL,
    ESTADO VARCHAR2(2) NOT NULL,
    CIDADE VARCHAR2(100) NOT NULL,
    BAIRRO VARCHAR2(100),
    DESCRICAO VARCHAR2(1000),
    CONSTRAINT FK_ONG_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE ACEITES_POLITICA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL,
    VERSAO_POLITICA VARCHAR2(20) NOT NULL,
    DATA_ACEITE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ACEITE_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID)
);
