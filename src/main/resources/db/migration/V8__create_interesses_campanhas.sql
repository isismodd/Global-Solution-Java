CREATE TABLE INTERESSES_CAMPANHAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CAMPANHA_ID NUMBER NOT NULL,
    USUARIO_ID NUMBER NOT NULL,
    TIPO_INTERESSE VARCHAR2(30) NOT NULL,
    DATA_INTERESSE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_INTERESSE_CAMPANHA
        FOREIGN KEY (CAMPANHA_ID)
        REFERENCES CAMPANHAS(ID),

    CONSTRAINT FK_INTERESSE_USUARIO
        FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIOS(ID),

    CONSTRAINT CK_INTERESSE_TIPO
        CHECK (TIPO_INTERESSE IN ('VOLUNTARIAR', 'PEDIDO_AJUDA')),

    CONSTRAINT UK_INTERESSE_CAMPANHA_USUARIO
        UNIQUE (CAMPANHA_ID, USUARIO_ID)
);