
-- V6 - Limpeza do legado ClyvoPet e adaptação da recuperação de senha

-- 1. Remover tokens antigos, já utilizados e expirados
DELETE FROM PASSWORD_RESET_TOKENS;

-- 2. Remover relacionamento antigo com VETERINARIOS
ALTER TABLE PASSWORD_RESET_TOKENS
    DROP CONSTRAINT FK_PRT_VETERINARIO;

-- 3. Adaptar a recuperação de senha para todos os usuários
ALTER TABLE PASSWORD_RESET_TOKENS
    RENAME COLUMN VETERINARIO_ID TO USUARIO_ID;

ALTER TABLE PASSWORD_RESET_TOKENS
    ADD CONSTRAINT FK_PRT_USUARIO
    FOREIGN KEY (USUARIO_ID)
    REFERENCES USUARIOS(ID);

-- 4. Remover o perfil antigo VETERINARIO
ALTER TABLE USUARIOS
    DROP CONSTRAINT CK_USUARIOS_PERFIL;

ALTER TABLE USUARIOS
    ADD CONSTRAINT CK_USUARIOS_PERFIL
    CHECK (PERFIL IN ('ADMIN', 'ONG', 'VOLUNTARIO', 'BENEFICIARIO'));

-- 5. Remover tabelas antigas na ordem correta
DROP TABLE LEMBRETES CASCADE CONSTRAINTS;
DROP TABLE CONSULTAS CASCADE CONSTRAINTS;
DROP TABLE ANIMAIS CASCADE CONSTRAINTS;
DROP TABLE VETERINARIOS CASCADE CONSTRAINTS;
