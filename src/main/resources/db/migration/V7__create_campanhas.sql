
CREATE TABLE CAMPANHAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ONG_ID NUMBER NOT NULL,
    TITULO VARCHAR2(150) NOT NULL,
    DESCRICAO VARCHAR2(2000) NOT NULL,
    CATEGORIA VARCHAR2(50) NOT NULL,
    LOCAL VARCHAR2(150) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ATIVA' NOT NULL,
    DATA_CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_CAMPANHA_ONG
        FOREIGN KEY (ONG_ID) REFERENCES ONGS(ID),

    CONSTRAINT CK_CAMPANHA_STATUS
        CHECK (STATUS IN ('ATIVA', 'INATIVA'))
);
